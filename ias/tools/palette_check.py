NAMES = ["平原", "丘陵", "山地", "高原", "盆地", "河谷", "荒漠", "草原", "森林", "湿地",
         "冰雪", "水", "喀斯特", "雅丹", "黄土", "沙丘", "冰川谷", "三角洲",
         "花岗岩山地", "喀斯特山地", "黄土山地", "火山山地", "冰蚀山地",
         "红壤丘陵", "黄土丘陵", "丹霞丘陵", "沙质荒漠", "砾质荒漠", "盐碱地"]

PAPER = 0.07
ALPHA = 0.34


def mix(a, b, t):
    return tuple(a[i] * (1 - t) + b[i] * t for i in range(3))


def render(c, shade=0.62):
    lum = c[0] * 0.35 + c[1] * 0.45 + c[2] * 0.20
    paper = (lum + 0.16, lum * 0.92 + 0.11, lum * 0.72 + 0.04)
    c1 = mix(c, paper, PAPER)
    k = 0.45 + 0.75 * shade
    return mix(c1, (0.30 * k, 0.27 * k, 0.22 * k), ALPHA)


def report():
    print("=== 陆地里偏蓝（b 明显 > r 或 > g） ===")
    bad = 0
    for i, c in enumerate(PAL):
        if i == 11:
            continue
        if c[2] > c[0] + 0.008 or c[2] > c[1] + 0.02:
            print("  %2d %-6s %s" % (i, NAMES[i], tuple(round(v, 2) for v in c)))
            bad += 1
    print("  偏蓝的陆地类：%d" % bad)
    for shade in (0.35, 0.62, 1.0):
        out = [render(c, shade) for c in PAL]
        pairs = []
        for i, j in itertools.combinations(range(29), 2):
            d = sum((out[i][k] - out[j][k]) ** 2 for k in range(3)) ** 0.5
            pairs.append((d, i, j))
        pairs.sort()
        print("=== shade=%.2f 最近 6 对 ===" % shade)
        for d, i, j in pairs[:6]:
            print("  %.3f  %s(%d) vs %s(%d)" % (d, NAMES[i], i, NAMES[j], j))


if __name__ == "__main__":
    report()

