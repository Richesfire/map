def dist_km(lon1, lat1, lon2, lat2):
    dx = (lon1 - lon2) * 111.32 * math.cos(math.radians((lat1 + lat2) / 2))
    dy = (lat1 - lat2) * 110.54
    return math.hypot(dx, dy)


def main():
    src_json = sys.argv[1] if len(sys.argv) > 1 else "ias-core/data/counties_han.json"
    exist_json = sys.argv[2] if len(sys.argv) > 2 else ""
    out_json = sys.argv[3] if len(sys.argv) > 3 else "ias-core/data/sites_han.json"
    counties = json.load(open(src_json, encoding="utf-8"))["counties"]

    out = []
    report = []
    for row in ROWS:
        name, kind, era, elon, elat, src, note = row[:7]
        match_name = row[7] if len(row) > 7 else name
        hit, hd = None, 1e9
        for c in counties:
            cn = c["n"]
            base = cn
            for suf in ("县", "国", "道", "邑"):
                if base.endswith(suf):
                    base = base[: -len(suf)]
                    break
            if base != match_name:
                continue
            d = dist_km(elon, elat, c["lon"], c["lat"])
            if d < hd:
                hd, hit = d, c
        if hit is not None and hd <= 60.0:
            lon, lat = hit["lon"], hit["lat"]
            coord_src = "CHGIS 汉县「%s」" % hit["n"]
        else:
            lon, lat = elon, elat
            coord_src = "考订（近似）"
        out.append({
            "id": "qm%02d" % (len(out) + 1),
            "name": name,
            "lon": round(lon, 3),
            "lat": round(lat, 3),
            "kind": kind,
            "era": era,
            "radius_km": 0.6,
            "src": src,
            "note": note,
            "coord_src": coord_src,
        })
        report.append((name, kind, coord_src, round(hd, 1) if hit else "-"))

    # 与既有 sites_han.json 合并：同名的以新表为准，其余原样保留
    old = []
    if exist_json and os.path.exists(exist_json):
        try:
            j = json.load(open(exist_json, encoding="utf-8"))
            old = j.get("sites", [])
        except Exception:
            old = []
    new_names = {s["name"] for s in out}
    merged = [s for s in old if s.get("name") not in new_names] + out

    doc = {
        "_comment": "秦汉史事点位（长平六处 + 秦末汉初 47 处）：城邑取 CHGIS 汉县坐标，"
                    "关/津/仓/战场为考订近似值。由 ias/tools/build_sites.py 生成，改之前先看脚本里的表。",
        "version": 2,
        "sites": merged,
    }
    with open(out_json, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
        f.write("\n")

    print("%-6s %-4s %-28s %s" % ("name", "kind", "coord", "与期望距离km"))
    for r in report:
        print("%-6s %-4s %-28s %s" % r)
    print("新增 %d 条，保留旧 %d 条 -> 共 %d 条，写出 %s"
          % (len(out), len(merged) - len(out), len(merged), out_json))


if __name__ == "__main__":
    main()
